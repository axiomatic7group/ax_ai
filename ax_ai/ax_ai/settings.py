if ENV_FILE.exists():
    with open(ENV_FILE) as open_env_file:
        for e_line in open_env_file:
            if e_line.strip() and not e_line.startswith('#'):
                key, value = e_line.strip().split("=", 1)
                os.environ[key] = value


